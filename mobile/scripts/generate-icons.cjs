// Render the existing Ionicons glyphs once; native screens only load the PNGs.
// Run with the repository's Playwright development dependency installed.
const fs = require('node:fs');
const path = require('node:path');
const { parse } = require('@babel/parser');
const { chromium } = require('playwright');

const projectRoot = path.resolve(__dirname, '..');
const sourceRoot = path.join(projectRoot, 'src');
const glyphMap = require('@expo/vector-icons/build/vendor/react-native-vector-icons/glyphmaps/Ionicons.json');
const fontPath = require.resolve('@expo/vector-icons/build/vendor/react-native-vector-icons/Fonts/Ionicons.ttf');

function iconNames(expression, names) {
  if (expression.type === 'JSXExpressionContainer') return iconNames(expression.expression, names);
  if (expression.type === 'ConditionalExpression') {
    iconNames(expression.consequent, names);
    iconNames(expression.alternate, names);
    return;
  }
  if (expression.type !== 'StringLiteral' || !(expression.value in glyphMap)) {
    throw new Error('Unsupported icon name at line ' + expression.loc.start.line + '. Use an Ionicons name literal.');
  }
  names.add(expression.value);
}

function collectNames(node, names) {
  if (!node || typeof node !== 'object') return;
  if (node.type === 'JSXOpeningElement' && node.name.name === 'Ionicons') {
    const attribute = node.attributes.find((item) => item.type === 'JSXAttribute' && item.name.name === 'name');
    if (!attribute?.value) throw new Error('An Ionicons component is missing its name.');
    iconNames(attribute.value, names);
  }
  for (const [key, value] of Object.entries(node)) {
    if (['loc', 'start', 'end', 'extra'].includes(key)) continue;
    if (Array.isArray(value)) value.forEach((item) => collectNames(item, names));
    else if (value && typeof value === 'object') collectNames(value, names);
  }
}

async function main() {
  const names = new Set();
  for (const file of fs.readdirSync(sourceRoot, { recursive: true })) {
    if (!file.endsWith('.js')) continue;
    const ast = parse(fs.readFileSync(path.join(sourceRoot, file), 'utf8'), { sourceType: 'module', plugins: ['jsx'] });
    collectNames(ast, names);
  }
  const sortedNames = [...names].sort();
  const browser = await chromium.launch({ headless: true });
  let rendered;
  try {
    const page = await browser.newPage();
    rendered = await page.evaluate(async ({ fontData, glyphs }) => {
      const font = new FontFace('SangeetXIcons', 'url(data:font/ttf;base64,' + fontData + ')');
      document.fonts.add(await font.load());
      return Object.fromEntries(glyphs.map(([name, codePoint]) => {
        const canvas = document.createElement('canvas');
        canvas.width = canvas.height = 256;
        const context = canvas.getContext('2d');
        context.font = '248px SangeetXIcons';
        context.fillStyle = '#ffffff';
        const glyph = String.fromCodePoint(codePoint);
        let metrics = context.measureText(glyph);
        let width = metrics.actualBoundingBoxLeft + metrics.actualBoundingBoxRight;
        let height = metrics.actualBoundingBoxAscent + metrics.actualBoundingBoxDescent;
        if (width <= 0 || height <= 0) throw new Error('Invalid glyph: ' + name);
        if (width > 248 || height > 248) {
          context.font = (248 * Math.min(248 / width, 248 / height)) + 'px SangeetXIcons';
          metrics = context.measureText(glyph);
          width = metrics.actualBoundingBoxLeft + metrics.actualBoundingBoxRight;
          height = metrics.actualBoundingBoxAscent + metrics.actualBoundingBoxDescent;
        }
        context.fillText(glyph, (256 - width) / 2 + metrics.actualBoundingBoxLeft,
          (256 - height) / 2 + metrics.actualBoundingBoxAscent);
        return [name, canvas.toDataURL('image/png').split(',')[1]];
      }));
    }, { fontData: fs.readFileSync(fontPath).toString('base64'), glyphs: sortedNames.map((name) => [name, glyphMap[name]]) });
  } finally {
    await browser.close();
  }

  const assetsRoot = path.join(projectRoot, 'assets', 'icons');
  fs.mkdirSync(assetsRoot, { recursive: true });
  let bytes = 0;
  for (const name of sortedNames) {
    const png = Buffer.from(rendered[name], 'base64');
    fs.writeFileSync(path.join(assetsRoot, name + '.png'), png);
    bytes += png.length;
  }
  const sources = sortedNames.map((name) => "  '" + name + "': require('../../assets/icons/" + name + ".png'),").join('\n');
  fs.writeFileSync(path.join(sourceRoot, 'theme', 'iconSources.js'),
    '// Generated by scripts/generate-icons.cjs. Metro requires static asset paths.\nexport const iconSources = {\n' + sources + '\n};\n');
  fs.copyFileSync(require.resolve('@expo/vector-icons/LICENSE'), path.join(assetsRoot, 'LICENSE'));
  console.log('Generated ' + sortedNames.length + ' native icons (256 x 256, ' + bytes + ' bytes total).');
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
